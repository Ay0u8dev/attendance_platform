export function buildMockStudentAttendanceOverview(): StudentAttendanceOverviewDto {
  const totalSessions = MOCK_STUDENT_ATTENDANCE_SUMMARIES.length;
  const presents = MOCK_STUDENT_ATTENDANCE_SUMMARIES.filter(
    (session) => session.attendanceStatus === 'PRESENT',
  ).length;
  const absences = MOCK_STUDENT_ATTENDANCE_SUMMARIES.filter(
    (session) => session.attendanceStatus === 'ABSENT',
  ).length;

  return {
    totalSessions,
    presents,
    absences,
    attendanceRate: totalSessions === 0 ? 0 : presents / totalSessions,
  };
}
